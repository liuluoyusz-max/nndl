"""Regenerate sections/member4_sections.tex from the individual section files.

The individual files are the source of truth; this script concatenates them in
report order so that member 5 has a single paste-ready file.  It also appends
the bibliography block, which lives at the end of the concatenated file only.

Usage:
    python _sync_sections.py
"""
from __future__ import annotations

from pathlib import Path

SECTIONS_DIR = Path(__file__).resolve().parent.parent / "sections"
OUT = SECTIONS_DIR / "member4_sections.tex"

# report order
ORDER = ("31", "33", "36", "37", "52")

HEADER = """%=========================================================================
% Member 4 sections: 3.1, 3.3, 3.6, 3.7, 5.2
% This file is generated by code/_sync_sections.py -- edit the
% sections/member4_<n>.tex files instead, then re-run the sync script.
% Requires in preamble (add alongside existing \\usepackage lines):
%   \\usepackage{booktabs}   % also fixes the current \\toprule compile error
%   \\usepackage{url}        % \\url in the bibliography (also missing upstream)
%=========================================================================
"""

BIBLIOGRAPHY = """
%==================================================
\\begin{thebibliography}{00}

\\bibitem{zhou2023dgsurvey}
K.~Zhou, Z.~Liu, Y.~Qiao, T.~Xiang, and C.~C.~Loy,
``Domain generalization: A survey,''
\\textit{IEEE Trans. Pattern Anal. Mach. Intell.}, vol.~45, no.~4, pp.~4396--4415, 2023.

\\bibitem{zhou2021mixstyle}
K.~Zhou, Y.~Yang, Y.~Qiao, and T.~Xiang,
``Domain generalization with MixStyle,''
in \\textit{Proc. Int. Conf. Learning Representations (ICLR)}, 2021.

\\bibitem{huang2017adain}
X.~Huang and S.~Belongie,
``Arbitrary style transfer in real-time with adaptive instance normalization,''
in \\textit{Proc. Int. Conf. Computer Vision (ICCV)}, 2017.

\\bibitem{li2017dg}
D.~Li, Y.~Yang, Y.-Z.~Song, and T.~Hospedales,
``Deeper, broader and artier domain generalization,''
in \\textit{Proc. Int. Conf. Computer Vision (ICCV)}, 2017.

\\bibitem{zhou2020dassl}
K.~Zhou, ``Dassl: Domain adaptation and generalization library,''
\\url{https://github.com/KaiyangZhou/Dassl.pytorch}, accessed 2026.

\\bibitem{he2016resnet}
K.~He, X.~Zhang, S.~Ren, and J.~Sun,
``Deep residual learning for image recognition,''
in \\textit{Proc. IEEE Conf. Computer Vision and Pattern Recognition (CVPR)}, pp.~770--778, 2016.

\\bibitem{zhang2018lpips}
R.~Zhang, P.~Isola, A.~A.~Efros, E.~Shechtman, and O.~Wang,
``The unreasonable effectiveness of deep features as a perceptual metric,''
in \\textit{Proc. IEEE Conf. Computer Vision and Pattern Recognition (CVPR)}, 2018.

\\bibitem{canny1986}
J.~Canny,
``A computational approach to edge detection,''
\\textit{IEEE Trans. Pattern Anal. Mach. Intell.}, vol.~8, no.~6, pp.~679--698, 1986.

\\bibitem{szegedy2016rethinking}
C.~Szegedy, V.~Vanhoucke, S.~Ioffe, J.~Shlens, and Z.~Wojna,
``Rethinking the Inception architecture for computer vision,''
in \\textit{Proc. IEEE Conf. Computer Vision and Pattern Recognition (CVPR)}, 2016.

\\bibitem{loshchilov2017sgdr}
I.~Loshchilov and F.~Hutter,
``{SGDR}: Stochastic gradient descent with warm restarts,''
in \\textit{Proc. Int. Conf. Learning Representations (ICLR)}, 2017.

\\end{thebibliography}

\\end{document}
"""


def main():
    parts = [HEADER]
    for key in ORDER:
        path = SECTIONS_DIR / f"member4_{key}.tex"
        if not path.is_file():
            raise SystemExit(f"missing section file: {path}")
        body = path.read_text(encoding="utf-8").rstrip()
        # The last section file also carries the bibliography and \end{document}
        # so that it can be compiled on its own.  Strip that tail here: the
        # merged file gets the bibliography once, at the end.
        for marker in ("\\begin{thebibliography}", "\\end{document}"):
            index = body.find(marker)
            if index != -1:
                body = body[:index].rstrip()
        # the individual files carry the "TODO (Member N)" marker above the
        # section heading; keep the marker so the merged draft still shows
        # where each section came from.
        parts.append(body)
        parts.append("\n%==================================================\n")
    parts.append(BIBLIOGRAPHY)

    OUT.write_text("\n".join(parts), encoding="utf-8")
    print(f"wrote {OUT} from {', '.join('member4_' + k + '.tex' for k in ORDER)}")


if __name__ == "__main__":
    main()
